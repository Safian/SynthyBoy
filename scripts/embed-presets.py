import argparse
import json
import os
import sys
from pathlib import Path


def escape_c_string(s: str) -> str:
    """Escape a string for C++ string literal."""
    out = []
    for c in s:
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif c == '\n':
            out.append('\\n')
        elif c == '\r':
            out.append('\\r')
        elif c == '\t':
            out.append('\\t')
        elif ord(c) < 32 or ord(c) >= 127:
            out.append(f'\\x{ord(c):02x}')
        else:
            out.append(c)
    return ''.join(out)


def collect_and_sort_presets(presets_dir: Path):
    presets = []
    for root, _, files in os.walk(presets_dir):
        for f in sorted(files):
            if f.endswith('.sbpreset'):
                full_path = Path(root) / f
                with open(full_path, 'r', encoding='utf-8') as fp:
                    content = fp.read()
                try:
                    data = json.loads(content)
                except Exception as e:
                    raise RuntimeError(f"Failed to parse JSON in {full_path}: {e}")

                meta = data.get('meta', {})
                category = meta.get('category', '')
                name = meta.get('name', '')
                if not category or not name:
                    raise RuntimeError(f"Missing category or name in {full_path}")

                rel_path = full_path.relative_to(presets_dir).as_posix()
                presets.append({
                    'category': category,
                    'name': name,
                    'rel_path': rel_path,
                    'content': content
                })

    # Canonical sorting algorithm:
    # 1. Sort by category ascending (case-sensitive <)
    # 2. Sort by name case-insensitively (ASCII tolower)
    # 3. Sort by relative file path
    def sort_key(p):
        return (p['category'], [c.lower() for c in p['name']], p['rel_path'])

    presets.sort(key=sort_key)
    return presets


def generate_header(out_h: Path):
    header_content = """// Generated by scripts/embed-presets.py. Do not edit.
#pragma once
#include <cstddef>

namespace synthyboy::desktop
{
struct EmbeddedPreset
{
    const char* category;
    const char* name;
    const char* jsonText;
    size_t jsonSize;
};

const EmbeddedPreset* getEmbeddedPresets (size_t& count) noexcept;
} // namespace synthyboy::desktop
"""
    out_h.parent.mkdir(parents=True, exist_ok=True)
    with open(out_h, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write(header_content)


def generate_cpp(out_cpp: Path, presets, header_include: str = "EmbeddedPresets.h"):
    lines = []
    lines.append("// Generated by scripts/embed-presets.py. Do not edit.")
    lines.append(f'#include "{header_include}"')
    lines.append("")
    lines.append("namespace synthyboy::desktop")
    lines.append("{")

    for i, p in enumerate(presets):
        var_name = f"p{i + 1:03d}_json"
        # We use R"sbpreset(...)sbpreset"
        if ")sbpreset" in p['content']:
            raise RuntimeError(f"Preset {p['rel_path']} contains ')sbpreset' raw string delimiter!")
        lines.append(f'static const char {var_name}[] = R"sbpreset({p["content"]})sbpreset";')

    lines.append("")
    lines.append("static const EmbeddedPreset kEmbeddedPresets[] = {")
    for i, p in enumerate(presets):
        var_name = f"p{i + 1:03d}_json"
        cat_esc = escape_c_string(p['category'])
        name_esc = escape_c_string(p['name'])
        lines.append(f'    {{ "{cat_esc}", "{name_esc}", {var_name}, sizeof({var_name}) - 1 }},')
    lines.append("};")
    lines.append("")
    lines.append("const EmbeddedPreset* getEmbeddedPresets (size_t& count) noexcept")
    lines.append("{")
    lines.append("    count = sizeof(kEmbeddedPresets) / sizeof(kEmbeddedPresets[0]);")
    lines.append("    return kEmbeddedPresets;")
    lines.append("}")
    lines.append("} // namespace synthyboy::desktop")
    lines.append("")

    out_cpp.parent.mkdir(parents=True, exist_ok=True)
    with open(out_cpp, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description="Embed factory presets into C++ source files.")
    parser.add_argument("--presets-dir", required=True, type=Path, help="Directory containing preset files")
    parser.add_argument("--out-h", required=True, type=Path, help="Output C++ header file path")
    parser.add_argument("--out-cpp", required=True, type=Path, help="Output C++ source file path")
    args = parser.parse_args()

    presets_dir = args.presets_dir.resolve()
    if not presets_dir.is_dir():
        sys.stderr.write(f"Error: presets directory not found: {presets_dir}\n")
        return 1

    presets = collect_and_sort_presets(presets_dir)
    generate_header(args.out_h.resolve())
    header_name = args.out_h.name
    generate_cpp(args.out_cpp.resolve(), presets, header_include=header_name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
