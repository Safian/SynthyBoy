import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "shell-mpc" / "overlay" / "backgrounds_manifest.h"
BG_SCRIPT = ROOT / "scripts" / "mpc-skin-extras" / "99_backgrounds.py"


def load_background_tabs(manifest=None):
    spec = importlib.util.spec_from_file_location("sb_99_backgrounds", BG_SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    tabs = mod.load_manifest(manifest) if manifest else getattr(mod, "BACKGROUND_TABS", [])
    return tabs, getattr(mod, "SENTINELS", {})


def render(tabs, sentinels):
    lines = [
        "// GENERATED by scripts/gen-backgrounds-manifest.py from scripts/mpc-skin-extras/99_backgrounds.py - do not edit by hand.",
        "// SynthyBoy - MPC overlay: the manifest of tabs that have pre-rendered static host page backgrounds in the skin.",
        "// Copyright (C) 2026 Safian Szabolcs",
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "#pragma once",
        "",
        "#include <cstring>",
        "",
        "namespace synthyboy_mpc { namespace overlay {",
        "",
        "struct BackgroundTab",
        "{",
        "    const char* viewName;",
        "    const char* tabName;",
        "    const char* assetFile;",
        "    int sentinelX, sentinelY;   // the 5 x 5 square of the sentinel, TAB coordinates (the host's picture must show sentinelRgb there before the plugin's plane may be transparent)",
        "    unsigned sentinelRgb;",
        "};",
        "",
        "// The tabs of scripts/mpc-skin-extras/overlay-backgrounds/manifest.json (EMPTY: no host background in the build); the last entry is a terminator that keeps the array non-empty.",
        "inline constexpr BackgroundTab kBackgroundTabs[] = {",
    ]
    for view_name, tab_name, asset_name in tabs:
        sx, sy, rgb = sentinels[view_name]
        lines.append(f'    {{ "{view_name}", "{tab_name}", "{asset_name}", {sx}, {sy}, 0x{rgb}u }},')
    lines += [
        "    { nullptr, nullptr, nullptr, 0, 0, 0u },",
        "};",
        "",
        f"inline constexpr int kNumBackgroundTabs = {len(tabs)};",
        "",
        "inline const BackgroundTab* backgroundOf (const char* viewName) noexcept",
        "{",
        "    if (viewName == nullptr)",
        "        return nullptr;",
        "    for (int i = 0; i < kNumBackgroundTabs; ++i)",
        "        if (std::strcmp (viewName, kBackgroundTabs[i].viewName) == 0)",
        "            return &kBackgroundTabs[i];",
        "    return nullptr;",
        "}",
        "",
        "inline bool hasHostBackground (const char* viewName) noexcept { return backgroundOf (viewName) != nullptr; }",
        "",
        "}} // namespace synthyboy_mpc::overlay",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="Output header path")
    ap.add_argument("--manifest", default=None, help="the tab list to use instead of overlay-backgrounds/manifest.json (the tests make the header of the [macros] state with it)")
    ap.add_argument("--check", action="store_true", help="Check that header matches generator without writing")
    args = ap.parse_args(argv)

    tabs, sentinels = load_background_tabs(args.manifest)
    missing = [t[0] for t in tabs if t[0] not in sentinels]
    if missing:
        print(f"99_backgrounds.py: no SENTINELS entry for {missing}", file=sys.stderr)
        return 1
    content = render(tabs, sentinels)
    out_path = Path(args.out)

    if args.check:
        if not out_path.is_file() or out_path.read_text(encoding="utf-8") != content:
            print(f"{out_path} is not current: run scripts/gen-backgrounds-manifest.py", file=sys.stderr)
            return 1
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
