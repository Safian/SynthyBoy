"""Generate the C++ Master geometry (shell-mpc/ui/master_native_layout.h) from the data the skin uses.

Usage: python3 scripts/gen-master-native-layout.py [--check]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/native_master/master_layout.json"
HEADER = ROOT / "shell-mpc/ui/master_native_layout.h"


def camel(text):
    return "".join(part[:1].upper() + part[1:] for part in text.replace(".", "_").replace(" ", "_").replace("&", "").split("_") if part)


def symbol(key):
    return "k" + camel(key[len("master."):] if key.startswith("master.") else key)


def rect(values):
    return "Rect { " + ", ".join(map(str, values)) + " }"


def render(layout):
    lines = ["// Generated by scripts/gen-master-native-layout.py from scripts/native_master/master_layout.json; do not edit.",
             "// Tab coordinates (1280 x 628). The skin (scripts/native_master/master_controls.py) places the native controls at the same rectangles.",
             "#pragma once", '#include "core.h"', "namespace synthyboy_mpc::ui::masterlayout {"]
    for key, value in layout["controls"].items():
        lines.append(f"constexpr Rect {symbol(key)} {rect(value)[5:]};")
    lines.append(f"constexpr Rect kLinkedBend {rect(layout['linked_bend'])[5:]};")
    lines.append(f"constexpr Rect kGlideCurve {rect(layout['glide_curve'])[5:]};")
    lines.append(f"constexpr Rect kScaleInput {rect(layout['scale_input'])[5:]};")
    for name, value in layout["output"].items():
        lines.append(f"constexpr Rect kOutput{camel(name)} {rect(value)[5:]};")
    for name, value in layout["side_buttons"].items():
        lines.append(f"constexpr Rect kSide{camel(name.split()[0].lower())} {rect(value)[5:]};")
    for caption in layout["captions"]:
        lines.append(f"constexpr Rect kCaption{camel(caption['text'].lower())} {rect(caption['rect'])[5:]};")
    panels = layout["panels"]
    lines.append(f"constexpr int kBlocks = {len(panels)};")
    lines.append("/** The titled block panels in reading order: " + ", ".join(p["title"] for p in panels) + ". */")
    lines.append("constexpr Rect kBlock[kBlocks] { " + ", ".join(rect(p["rect"]) for p in panels) + " };")
    lines.append("constexpr bool kBlockOnTuning[kBlocks] { " + ", ".join("true" if p["side"] == "tuning" else "false" for p in panels) + " };")
    lines.append("constexpr const char* kBlockTitle[kBlocks] { " + ", ".join(f'"{p["title"]}"' for p in panels) + " };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the header is stale")
    args = parser.parse_args()
    text = render(json.loads(SOURCE.read_text()))
    if args.check:
        sys.exit(0 if HEADER.is_file() and HEADER.read_text() == text else 1)
    HEADER.write_text(text)


if __name__ == "__main__":
    main()
