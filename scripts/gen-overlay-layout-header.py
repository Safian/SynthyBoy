# Usage: python3 scripts/gen-overlay-layout-header.py [--json FILE] [--out FILE | --check]
#   default: writes shell-mpc/overlay/overlay_layout.h next to the JSON; --check exits 1 when the header on disk is not what the JSON generates.
# The JSON is the single source of the views (region, marker squares and their colours, the instance picture and its colour table): the skin module (scripts/mpc-skin-extras/50_filter_overlay.py) reads it
# directly, the plugin includes the generated header. The header is committed; scripts/tests/test_mpc_skin_overlay.py checks that it is current.

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_JSON = ROOT / "shell-mpc" / "overlay" / "overlay_layout.json"
DEFAULT_OUT = ROOT / "shell-mpc" / "overlay" / "overlay_layout.h"


def rgb(text):
    if len(text) != 6 or any(c not in "0123456789abcdef" for c in text.lower()):
        raise ValueError("colour %r is not 6 hex digits" % text)
    return int(text, 16)


KINDS = {"filter": 0, "lfo": 1, "osc": 2, "env": 3, "spectrum": 4}


def render(layout):
    origin = layout["tabOriginY"]
    views = layout["views"]
    seen = {}
    for v in views:
        if v["kind"] not in KINDS:
            raise ValueError("view %r: unknown kind %r" % (v["name"], v["kind"]))
        if len(v["markers"]) != 2:
            raise ValueError("view %r needs exactly two markers" % v["name"])
        for m in v["markers"]:
            c = rgb(m["rgb"])
            rgb(m["cover"])
            for other, oc in seen.items():
                if all(abs(((c >> s) & 255) - ((oc >> s) & 255)) <= 4 for s in (0, 8, 16)):
                    raise ValueError("marker colour %s of %r is within the detector's tolerance of the marker colour of %r" % (m["rgb"], v["name"], other))
            seen["%s/%s" % (v["name"], m["rgb"])] = c
    row = layout["meterRow"]
    row_w = row["columns"] * row["columnW"] + (row["columns"] - 1) * row["gap"]
    for v in views:
        if v["kind"] == "spectrum" and v["region"] != {"x": row["x"], "y": row["y"], "w": row_w, "h": row["h"]}:
            raise ValueError("view %r: the region is not the bounding box of the row of the meters (meterRow)" % v["name"])
    inst = layout["instance"]
    if inst["slots"] != 16 or len(inst["slotColours"]) != inst["slots"] or inst["frames"] != inst["steps"] + 1 or inst["slots"] + 2 > inst["frames"]:
        raise ValueError("instance: 16 slot colours, frames = steps + 1, room for blank + 16 slots + none")
    inst_colours = {"slot%d" % k: rgb(c) for k, c in enumerate(inst["slotColours"])}
    inst_colours["none"], inst_colours["blank"] = rgb(inst["none"]), rgb(inst["blank"])
    names = list(inst_colours)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if all(abs(((inst_colours[a] >> s) & 255) - ((inst_colours[b] >> s) & 255)) <= 4 for s in (0, 8, 16)):
                raise ValueError("instance colours %s and %s are within the detector's tolerance of each other" % (a, b))
    others = dict(seen)
    others["background"] = rgb(layout["background"])
    for v in views:
        for m in v["markers"]:
            others["cover/%s" % m["cover"]] = rgb(m["cover"])
    for a in names:
        for b, oc in others.items():
            if all(abs(((inst_colours[a] >> s) & 255) - ((oc >> s) & 255)) <= 4 for s in (0, 8, 16)):
                raise ValueError("instance colour %s is within the detector's tolerance of %s" % (a, b))
    for v in views:
        i, r = v["instance"], v["region"]
        if not (r["x"] <= i["x"] and i["x"] + i["w"] <= r["x"] + r["w"] and r["y"] <= i["y"] and i["y"] + i["h"] <= r["y"] + r["h"]):
            raise ValueError("view %r: the instance picture is not inside its region" % v["name"])
        if i["w"] < 4 or i["h"] < 4:
            raise ValueError("view %r: the instance picture is smaller than 4 x 4" % v["name"])
        for m in v["markers"]:
            if i["x"] < m["x"] + m["w"] + 1 and m["x"] < i["x"] + i["w"] + 1 and i["y"] < m["y"] + m["h"] + 1 and m["y"] < i["y"] + i["h"] + 1:
                raise ValueError("view %r: the instance picture touches a marker" % v["name"])
    lines = [
        "// GENERATED by scripts/gen-overlay-layout-header.py from shell-mpc/overlay/overlay_layout.json - do not edit by hand.",
        "// SynthyBoy - MPC overlay: the views (region of a tab + two marker squares + the instance picture each) of the overlay skin, in SCREEN coordinates (landscape UI, 1280 x 800).",
        "// Copyright (C) 2026 Safian Szabolcs",
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "#pragma once",
        "",
        "namespace synthyboy_mpc { namespace overlay { namespace layout {",
        "struct Rect { int x, y, w, h; };",
        "struct Marker { Rect rect; unsigned rgb; unsigned cover; };   // cover: the colour of what lies under the marker (a transparent view paints it over the marker)",
        "constexpr int kKindFilter = 0, kKindLfo = 1, kKindOsc = 2, kKindEnv = 3, kKindSpectrum = 4;",
        "struct View { const char* name; int kind; int index; Rect region; bool opaque; Marker markers[2]; Rect instance; };   // instance: the film strip image bound to the display parameter \"Overlay Instance\" (one frame = this size)",
        "constexpr int kScreenW = %d;" % layout["screen"]["width"],
        "constexpr int kScreenH = %d;" % layout["screen"]["height"],
        "constexpr int kTabOriginY = %d;" % origin,
        "constexpr unsigned kBackgroundRgb = 0x%06x;   // the colour of the dark picture of an opaque view" % rgb(layout["background"]),
        "constexpr int kMaxInstances = %d;   // slots 0 .. kMaxInstances - 1: the instances beyond them get none and never show the overlay" % inst["slots"],
        "constexpr int kInstanceFrames = %d;   // frames of the film strip: 0 blank, 1 .. 16 slot 0 .. 15, 17 none, the rest blank" % inst["frames"],
        "constexpr int kInstanceSteps = %d;   // the parameter's value of frame f is f / kInstanceSteps (exact in a float)" % inst["steps"],
        "constexpr unsigned kInstanceSlotRgb[kMaxInstances] = { %s };" % ", ".join("0x%06x" % rgb(c) for c in inst["slotColours"]),
        "constexpr unsigned kInstanceNoneRgb = 0x%06x;    // frame 17: an instance without a slot" % rgb(inst["none"]),
        "constexpr unsigned kInstanceBlankRgb = 0x%06x;   // frame 0 (nothing reported yet) and the frames after 17" % rgb(inst["blank"]),
        "constexpr int kNumViews = %d;" % len(views),
        "constexpr View kViews[kNumViews] = {",
    ]
    for v in views:
        r = v["region"]
        ms = ", ".join("{ { %d, %d, %d, %d }, 0x%06x, 0x%06x }" % (m["x"], m["y"] + origin, m["w"], m["h"], rgb(m["rgb"]), rgb(m["cover"])) for m in v["markers"])
        i = v["instance"]
        lines.append('    { "%s", %d, %d, { %d, %d, %d, %d }, %s, { %s }, { %d, %d, %d, %d } },   // tab "%s"' % (v["name"], KINDS[v["kind"]], v["index"], r["x"], r["y"] + origin, r["w"], r["h"],
                                                                                "true" if v["opaque"] else "false", ms, i["x"], i["y"] + origin, i["w"], i["h"], v["tab"]))
    lines += ["};", "}}} // namespace synthyboy_mpc::overlay::layout", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=str(DEFAULT_JSON))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(json.loads(Path(args.json).read_text(encoding="utf-8")))
    out = Path(args.out)
    if args.check:
        if not out.is_file() or out.read_text(encoding="utf-8") != text:
            print("%s is not current: run scripts/gen-overlay-layout-header.py" % out, file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
