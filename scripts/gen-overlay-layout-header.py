#   default: writes shell-mpc/overlay/overlay_layout.h next to the JSON; --check exits 1 when the header on disk is not what the JSON generates.
# The JSON is the single source of the curve area and the two marker pictures: the skin module (scripts/mpc-skin-extras/50_filter_overlay.py) reads it
# directly, the plugin includes the generated header. The header is committed; scripts/tests/test_mpc_skin_overlay.py checks that it is current.

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_JSON = ROOT / "shell-mpc" / "overlay" / "overlay_layout.json"
DEFAULT_OUT = ROOT / "shell-mpc" / "overlay" / "overlay_layout.h"


def rgb(text):
    if len(text) != 6 or any(c not in "0123456789abcdef" for c in text.lower()):
        raise ValueError("colour %r is not 6 hex digits" % text)
    return int(text, 16)


def render(layout):
    origin = layout["tabOriginY"]
    c = layout["curve"]
    lines = [
        "// GENERATED by scripts/gen-overlay-layout-header.py from shell-mpc/overlay/overlay_layout.json - do not edit by hand.",
        "// SynthyBoy - MPC overlay: the curve area and the marker pictures of the overlay skin, in SCREEN coordinates (landscape UI, 1280 x 800).",
        "// Copyright (C) 2026 Safian Szabolcs",
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "#pragma once",
        "",
        "namespace synthyboy_mpc { namespace overlay { namespace layout {",
        "struct Rect { int x, y, w, h; };",
        "struct Marker { Rect rect; unsigned rgb; };",
        "constexpr int kScreenW = %d;" % layout["screen"]["width"],
        "constexpr int kScreenH = %d;" % layout["screen"]["height"],
        "constexpr int kTabOriginY = %d;" % origin,
        "constexpr Rect kCurve = { %d, %d, %d, %d };   // the area the curve is drawn in" % (c["x"], c["y"] + origin, c["w"], c["h"]),
        "constexpr unsigned kBackgroundRgb = 0x%06x;   // the colour of the skin picture behind the curve; the overlay paints it over the markers" % rgb(layout["background"]),
        "constexpr int kNumMarkers = %d;" % len(layout["markers"]),
        "constexpr Marker kMarkers[kNumMarkers] = {",
    ]
    for m in layout["markers"]:
        lines.append("    { { %d, %d, %d, %d }, 0x%06x },   // %s" % (m["x"], m["y"] + origin, m["w"], m["h"], rgb(m["rgb"]), m["name"]))
    lines += ["};", "}}} // namespace synthyboy_mpc::overlay::layout", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=str(DEFAULT_JSON))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(json.loads(Path(args.json).read_text(encoding="utf-8")))
    out = Path(args.out)
    if args.check:
        if not out.is_file() or out.read_text(encoding="utf-8") != text:
            print("%s is not current: run scripts/gen-overlay-layout-header.py" % out, file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
