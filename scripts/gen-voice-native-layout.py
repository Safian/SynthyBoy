#!/usr/bin/env python3
"""Generate C++ Voice native geometry from the same data used by the skin."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
contract = json.loads((ROOT/'scripts/native_voice/voice_layout.json').read_text())
lines = ['// Generated by scripts/gen-voice-native-layout.py; do not edit.', '#pragma once', '#include "core.h"',
         'namespace synthyboy_mpc::ui::voicelayout {']
for c in contract['controls']:
    name = c['name'].replace('Voice ','').replace(' ','')
    lines.append('constexpr Rect k'+name+' { '+', '.join(map(str,c['rect']))+' };')
for name,kind,rect,caption,key in contract['sequence']:
    symbol=name.replace('Voice ','').replace(' ','')
    lines.append('constexpr Rect k'+symbol+' { '+', '.join(map(str,rect))+' };')
steps=contract['steps']
lines.append('constexpr Rect kSequenceGrid { '+', '.join(map(str,steps['rect']))+' };')
for key in ('pad','gap','diameter','top','value_gap'):
    lines.append('constexpr int kStep'+''.join(p.title() for p in key.split('_'))+' = '+str(steps[key])+';')
lines.append('}\n')
(ROOT/'shell-mpc/ui/voice_native_layout.h').write_text('\n'.join(lines))
