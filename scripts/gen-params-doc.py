import json
import sys

# What the engines can do that the parameter table does not expose, and what is pending (docs/PARAMETERS.md, last section).
NOT_EXPOSED = [
    ("Sample oscillator", "pending (Phase 4): it needs content packs (docs/ARCHITECTURE.md section 6). The engine has one; the "
                          "noise oscillator above is its built-in white noise."),
    ("Free-form LFO shapes / wavetable editing", "pending (Phase 5, UI): LFOs use the built-in shape list and oscillators the "
                                                 "built-in wavetables; there is no editor and no import yet."),
    ("Tuning root (A4 reference), tuning tables", "not exposed: the engine's tuning object is a scale/keyboard-map loader "
                                                  "(no reference frequency); this build plays 12-tone equal temperament at A4 = 440 Hz."),
    ("Oscillator MIDI tracking (fixed pitch), transpose quantize", "not exposed: not part of the feature list; the engine has them."),
    ("Spectral unison switch", "not exposed: always on (the engine default)."),
    ("Per-oscillator smooth interpolation switch", "not a parameter: it is the quality tier's wavetable interpolation "
                                                   "(linear on Low and Medium, spectral on High)."),
    ("Oversampling", "not a parameter: it is the quality tier's (1x on Low, 2x otherwise)."),
    ("Stereo mode / routing, view settings, MPE, bypass, tempo control", "not exposed: host / UI business, not sound design."),
    ("Mod sources lift, slide, stereo, note-in-octave", "not exposed: the event contract has no lift/slide and the matrix list "
                                                        "is the one of docs/ARCHITECTURE.md 3.5."),
    ("Line-map curve of a modulation slot", "not exposed: free-form curve editing (the slot keeps the linear map); the "
                                            "'curve' parameter (power) is exposed."),
    ("Voice priority / override, keytracked portamento options beyond the four listed", "not exposed: voice stealing is "
                                                                                       "'oldest' (documented in core/engine-vital/README.md)."),
]

UNIT_LABEL = {"none": "", "dB": "dB", "Hz": "Hz", "ms": "ms", "percent": "%", "semitone": "st", "cents": "ct",
              "beats": "beats", "degrees": "deg", "voices": "voices"}


def fmt(v):
    if v == int(v) and abs(v) < 1e9:
        return str(int(v))
    return ("%.9g" % v)


def esc(s):
    return s.replace("|", "\\|")


def range_text(p, doc):
    unit = UNIT_LABEL[p["unit"]]
    if p["scale"] == "stepped":
        if "choices" in p:
            names = p["choices"]
            if len(names) > 6:
                shown = ", ".join("%d %s" % (i, n) for i, n in enumerate(names[:3])) + ", ... , %d %s" % (len(names) - 1, names[-1])
                return "%d choices: %s" % (len(names), esc(shown))
            return esc(", ".join("%d %s" % (i, n) for i, n in enumerate(names)))
        if p.get("choiceSet") == "modSource":
            return "0 None, 1..%d sources (list below)" % len(doc["modSources"])
        return "0 None, 1..%d destinations (list below)" % len(doc["modDestinations"])
    shape = ""
    if p["scale"] == "exp_skew":
        shape = " (skew %s)" % fmt(p["skew"])
    if p["interval"] > 0:
        shape += " (steps of %s)" % fmt(p["interval"])
    return "%s .. %s%s%s" % (fmt(p["min"]), fmt(p["max"]), (" " + unit) if unit else "", shape)


def default_text(p):
    if p["scale"] == "stepped" and "choices" in p:
        return esc(p["choices"][int(p["default"])])
    if p["scale"] == "stepped":
        return "None"
    unit = UNIT_LABEL[p["unit"]]
    return fmt(p["default"]) + ((" " + unit) if unit else "")


def main():
    if len(sys.argv) != 3:
        print("usage: gen-params-doc.py params.json PARAMETERS.md", file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        doc = json.load(f)
    params = doc["params"]

    out = []
    w = out.append
    w("# SynthyBoy - parameters")
    w("")
    w("<!-- Generated by scripts/gen-params-doc.py from docs/params.json (build/tools/paramdump/synthyboy_paramdump). Do not edit. -->")
    w("")
    w("The parameter table is our own design (`core/src/param_table.cpp`, docs/ARCHITECTURE.md 2.2 and 5.1): keys are lowercase and "
      "dotted, ranges are in our units (Hz, ms, dB, cents, semitones, percent, degrees, beats) and are inside what the engines "
      "can do. `docs/params.json` is the same table for machines (Kick's own UI reads it). State format version %d stores every "
      "parameter by key (docs/ARCHITECTURE.md 5.2)." % doc["stateVersion"])
    w("")
    w("**%d parameters.** Column *own engine*: yes = the own engine (`core/engine-own`, the engine of iOS builds) acts on the "
      "parameter; every parameter is stored, saved and read back by every engine, the engine of the Vital-derived DSP "
      "(`core/engine-vital`) acts on all of them." % doc["count"])
    w("")

    # summary by top level group
    groups = {}
    order = []
    for p in params:
        top = p["group"].split(" / ")[0]
        if top not in groups:
            groups[top] = []
            order.append(top)
        groups[top].append(p)
    w("| Section | Parameters |")
    w("|---------|------------|")
    for top in order:
        w("| %s | %d |" % (top, len(groups[top])))
    w("")

    w("## Default patch")
    w("")
    w("A clean, basic saw patch: oscillator 1 on (built-in Saw, one voice, centred, level 50 %), filter 1 on (Digital model, "
      "low-pass, 12 kHz, 20 % resonance), envelope 1 with a 5 ms attack, 400 ms decay to 100 % sustain and 200 ms release, master "
      "volume -12 dB, polyphony 16, no effects, all 64 modulation slots empty. Oscillators 2 and 3, the noise and the other "
      "filters are off. Written from the table's defaults, not from any preset.")
    w("")

    w("## Parameters by section")
    w("")
    w("Modulation: parameters marked *mod* can be the destination of a modulation slot. A slot's amount (-100 .. 100 %) is a "
      "fraction of the destination's range **in the engine's own scale** (for the filter cutoff that is the whole keyboard range "
      "in semitones, not Hz). A slot whose wiring would close a loop (its source depends on its destination, for example one LFO "
      "modulating the rate of another that modulates the first) stays unwired, because the engine would have to allocate on the audio "
      "thread to build it.")
    w("")
    for top in order:
        w("### %s" % top)
        w("")
        w("| Key | Name | Range | Default | Group | Mod | Own engine |")
        w("|-----|------|-------|---------|-------|-----|------------|")
        shown_slots = 0
        for p in groups[top]:
            if p["key"].startswith("mod") and p["key"][3:5].isdigit() and p["key"][3:5] != "01":
                continue
            key = p["key"]
            name = p["name"]
            if p["key"].startswith("mod01."):
                key = "modNN." + p["key"].split(".", 1)[1]
                name = name.replace("Mod 01", "Mod NN") + " (NN = 01 .. 64)"
            w("| `%s` | %s | %s | %s | %s | %s | %s |" % (key, esc(name), range_text(p, doc), default_text(p),
                                                      esc(p["group"]), "mod" if p["modulatable"] else "",
                                                      "yes" if p["ownEngine"] else ""))
        if top == "Mod Matrix":
            w("")
            w("The matrix has %d identical slots `mod01` .. `mod64` (only the first is listed). A slot with source *None* or "
              "destination *None* does nothing. *Bipolar* centres a 0..1 source around zero, *Stereo* inverts the amount in the "
              "right channel, *Bypass* mutes the slot, *Curve* bends the source (negative = fast start, positive = slow start)." )
        w("")

    w("## Modulation sources")
    w("")
    w("Choice values of `modNN.source` (0 = None).")
    w("")
    w("| Value | Key | Name | Polarity |")
    w("|-------|-----|------|----------|")
    for s in doc["modSources"]:
        w("| %d | `%s` | %s | %s |" % (s["choice"], s["key"], esc(s["name"]), "bipolar" if s["bipolar"] else "unipolar"))
    w("")

    w("## Modulation destinations")
    w("")
    w("Choice values of `modNN.destination` (0 = None): every parameter flagged *mod*, in table order. The label of a choice is the "
      "parameter's name.")
    w("")
    w("| Value | Key | Name |")
    w("|-------|-----|------|")
    for d in doc["modDestinations"]:
        w("| %d | `%s` | %s |" % (d["choice"], d["key"], esc(d["name"])))
    w("")

    w("## Built-in wavetables and LFO shapes")
    w("")
    for p in params:
        if p["key"] in ("osc1.wavetable", "lfo1.shape"):
            w("* `%s`: %s" % (p["key"].split(".")[1] + " (all instances)", ", ".join("%d %s" % (i, n) for i, n in enumerate(p["choices"]))))
    w("")
    w("They are generated by code in the engine adapter (no file, no preset, no third-party content). The own engine plays Sine for "
      "entry 0 and Saw for every other entry.")
    w("")

    w("## Quality tiers")
    w("")
    w("A tier only caps or bypasses (docs/ARCHITECTURE.md 3.6); parameter values are never changed.")
    w("")
    w("| | Low | Medium | High |")
    w("|-|-----|--------|------|")
    w("| Max voices | 8 | 16 | 32 |")
    w("| Max unison voices per oscillator | 4 | 8 | 16 |")
    w("| Oversampling | 1x | 2x | 2x |")
    w("| Wavetable frame interpolation | linear | linear | spectral |")
    w("| Effects bypassed | reverb, flanger | none | none |")
    w("")

    w("## Not exposed")
    w("")
    for title, text in NOT_EXPOSED:
        w("* **%s**: %s" % (title, text))
    w("")

    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
