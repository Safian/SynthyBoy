import argparse
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import wavetable_lib as wl  # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, ".."))
REPORT = os.path.join(REPO, "docs", "release", "WAVETABLE-PACK.md")
GUIDE = os.path.join(REPO, "docs", "user-guide", "factory-content.md")
BEGIN, END = "<!-- wavetable-catalogue:begin -->", "<!-- wavetable-catalogue:end -->"

NATURE = {   # tables whose level spread is by nature (a click, a burst) or whose frames are stepped
    "crackle_pulses": "frames hold 3 to 64 clicks: the level evens out only as far as the peak limit allows",
    "noise_burst_widening": "a narrow burst has a high crest factor: the peak limit stops the level evening",
}

SUGGESTIONS = [
    ("Analog / Saw Filter Sweep", "bass and lead presets that need a built-in filter sweep driven by one macro or the mod wheel (frame = cutoff); cheap alternative to a filter envelope."),
    ("Analog / Saw Stack Spread", "supersaw-like pads and trance leads: frame position on an LFO or on velocity widens the stack without unison cost."),
    ("Analog / Sync Sine Sweep and Sync Saw Sweep", "screaming mono leads and bass: frame on the pitch envelope or velocity gives the classic sync sweep."),
    ("Digital / FM Chain 1-2-3", "electric piano, bell and mallet presets: frame on a decaying envelope (key down 0, tail 63) for the index decay; set Osc B to a sine one octave down."),
    ("Digital / Phase Distortion Resonance", "acid-style basses and squelchy plucks: frame on an envelope with fast decay."),
    ("Spectral / Bore Odd To Even", "reed, clarinet and sax-like leads: frame on breath or aftertouch."),
    ("Spectral / Harmonic Band Sweep", "wah and talking basses with the frame on an LFO or an envelope follower; also good as a spectral filter table."),
    ("Vocal / Vowel Cycle Women and Vowel Cycle Men", "vocal pads and talk-box leads: frame on slow LFO or mod wheel; keep the played range within an octave around 130 Hz (men) or 220 Hz (women)."),
    ("Vocal / Choir Blend", "choir pads with a long attack: Osc A on the table, a second oscillator one octave up at low level, chorus and reverb."),
    ("Metallic / Bell Pitch Walk and Free Bar Modes", "mallet, vibraphone and bell presets where the frame follows velocity (harder = brighter): the partials shift as the frame moves."),
    ("Metallic / Gong Modes Swell and Cymbal Cloud", "reverse-swell pads, cymbal-like risers and impacts: frame on a slow rising envelope."),
    ("Noise / Noise Band Sweep and Breath Air Bumps", "wind, riser and breath layers (Osc B at low level under a tonal oscillator); frame on a rising envelope for sweeps."),
]


def load():
    spec = importlib.util.spec_from_file_location("gcp_docs", os.path.join(HERE, "gen-content-pack.py"))
    g = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(g)
    rows = []
    for e in g.load_recipes(g.RECIPES_ROOT):
        data = wl.table_samples(e["recipe"], e["slug"])
        rows.append((e, wl.measures(data), len(g.wav_bytes(data * 1.0))))
    return g, rows


def pack_sizes():
    out = {}
    for name in ("presets", "factory-wavetables", "factory-samples"):
        t = 0
        for dp, _, fns in os.walk(os.path.join(REPO, "content", name)):
            t += sum(os.path.getsize(os.path.join(dp, f)) for f in fns)
        out[name] = t
    return out


def catalogue(rows):
    lines = [BEGIN, "", "_Generated by `scripts/gen-wavetable-docs.py` from the recipes in `content-src/wavetables/`; edit the recipe's `description`, not this block._", ""]
    for cat in wl.CATEGORIES:
        mine = [r for r in rows if r[0]["category"] == cat]
        lines += [f"### {cat} ({len(mine)} tables)", "", "| Table | File | Frames | What the scan does |", "|---|---|---|---|"]
        for e, m, size in mine:
            lines.append(f"| {e['recipe']['title']} | `{cat}/{e['slug']}.wav` | {m['frames']} | {e['recipe']['description']} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def report(g, rows):
    sz = pack_sizes()
    wt = sz["factory-wavetables"]
    allc = sum(sz.values())
    before = {"factory-wavetables": 3800674, "presets": 8107237, "factory-samples": 7691826}
    L = ["# Wavetable pack: quality report", "",
         "Generated by `scripts/gen-wavetable-docs.py` (numbers measured on the rendered files). Status: **measured, NOT HEARD** (the author cannot hear): the numbers say the tables are clean and even, not that they are beautiful. The owner's ears decide.", "",
         "## Format", "",
         "16 bit mono PCM WAV, 44.1 kHz header, 2048 samples per frame, 64 frames unless the table is by nature shorter (the first 16 tables keep their 31, 32 and 48 frame lengths). This is what "
         "`core/engine-own/osc/content_set.cpp` reads: `sampleosc::readWav`, then `frames = samples / 2048` (at most 256), `makeWavetableFromSamples` (per frame: the mean is removed and kept as DC, FFT, the engine builds its own mip levels). "
         "The reader walks the RIFF chunks and skips unknown ones (`wav_reader.cpp`), so a `clm ` chunk would be ignored. **No `clm ` chunk is written**: the engine does not need it, and the 16 existing files must stay byte for byte what they were "
         "(presets name them by SHA-256); an external tool that wants the chunk can add it without touching the samples.", "",
         "## What is measured", "",
         "- **Peak**: largest absolute sample of the table (full scale 1.0). The new tables are levelled to an RMS of 0.35 per frame with a peak limit of 0.9, so every table has headroom; the first 16 are peak-normalised per frame to 0.9 (their original convention).",
         "- **Level spread**: highest minus lowest per-frame RMS in dB: how much the level jumps while scanning (0 = even).",
         "- **Highest harmonic**: the highest harmonic whose amplitude is within 60 dB of the table's strongest harmonic, over all frames (the band limit that matters; the writer cuts every frame at its `limit`, 250 to 700).",
         "- **DC**: largest absolute mean of a frame (written frames have no DC; values around 1e-17 are rounding).", "",
         f"## Size", "",
         f"Wavetables: **{wt} bytes ({wt / 1e6:.1f} MB)**, was {before['factory-wavetables']} ({before['factory-wavetables'] / 1e6:.1f} MB). The whole `Content/` folder (presets + wavetables + samples, instruments, impulses): **{allc} bytes ({allc / 1e6:.1f} MB, {allc / 1048576:.1f} MiB)**, "
         f"was {sum(before.values())} ({sum(before.values()) / 1e6:.1f} MB, {sum(before.values()) / 1048576:.1f} MiB). The package, about 40 MB with 18.7 MiB of content, therefore becomes about {40 + (allc - sum(before.values())) / 1048576:.0f} MB. "
         "The wavetables stay under the 25 MB line, so no table had to be cut; if the size ever has to shrink, the candidates are the 64 frame tables whose scan is slow (Colour Tilt Sweep, Spectral Tilt Sweep, Pink Lowpass Sweep, Gong Modes Swell, Tract Length Sweep, Breathy To Pressed): 32 frames lose nothing audible there.", "",
         "## The tables", "",
         "| Category | Title | Frames | What the scan does | Peak | Level spread dB | Highest harmonic | DC |", "|---|---|---|---|---|---|---|---|"]
    for e, m, size in rows:
        note = f" ({NATURE[e['slug']]})" if e["slug"] in NATURE else ""
        L.append(f"| {e['category']} | {e['recipe']['title']} | {m['frames']} | {e['recipe']['description']}{note} | {m['peak']:.2f} | {m['spread_db']:.1f} | {m['highest_harmonic']} | {m['dc']:.0e} |")
    sp = sorted(rows, key=lambda r: -r[1]["spread_db"])[:6]
    L += ["", "Largest level spreads: " + ", ".join(f"{e['recipe']['title']} {m['spread_db']:.1f} dB" for e, m, _ in sp) + ". Where the spread is over 4 dB the peak limit stops the evening (a very peaky frame: a click, a narrow pulse, a bright buzzy saw); "
          "the first 16 tables, normalised by peak, have larger RMS spreads by construction.", "",
          "## Twelve suggestions for the sound-set work", ""]
    for i, (t, s) in enumerate(SUGGESTIONS, 1):
        L.append(f"{i}. **{t}**: {s}")
    L += ["", "## What is not certain", "",
          "- Nothing here was listened to. Vowel tables use harmonic positions of one pitch (see each table's pitch in its description): at other pitches the formants move with the pitch.",
          "- The inharmonic metallic tables put real-valued partial positions on the integer harmonic grid by splitting each partial between two neighbours: a movement of the partials is a cross fade of two harmonics, which sounds a little like a chorus on slow scans.",
          "- The oscillator cuts at its own mip levels: tables that are bright up to 300 to 400 harmonics are filtered at high notes by the engine; check the top octave by ear.", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    g, rows = load()
    out = {REPORT: report(g, rows)}
    guide = open(GUIDE, "r", encoding="utf-8").read()
    if BEGIN in guide:
        s = guide[:guide.index(BEGIN)] + catalogue(rows) + guide[guide.index(END) + len(END) + 1:]
    else:
        s = guide
    out[GUIDE] = s
    bad = [p for p, t in out.items() if not os.path.isfile(p) or open(p, "r", encoding="utf-8").read() != t]
    if a.check:
        print("docs up to date" if not bad else "docs differ: " + ", ".join(bad))
        return 1 if bad else 0
    for p, t in out.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(t)
    print("wrote " + ", ".join(os.path.relpath(p, REPO) for p in out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
