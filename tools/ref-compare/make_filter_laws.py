#!/usr/bin/env python3
"""SynthyBoy - ref-compare: turns the measured filter level differences (fit_filter.py --identity-only --json, Serum - ours in dB of the sustain rms, per type, cutoff and resonance) into
core/serum-import/serum_filter_laws.inc, the table the Serum importer adds to the level of a filter (serum_map.cpp, filterResoLevelDb).

  make_filter_laws.py MEASURED.json [--out core/serum-import/serum_filter_laws.inc] [--data docs/ui-design/refcompare-filter-laws.json] [--drive DRIVE_MEASURED.json]

The grid is cutoff 0.35 / 0.5 / 0.65 / 0.8 (the Serum file value) x resonance 0 / 10 / 20 / 35 / 50 / 75 / 100; a type with all differences under 1 dB is left out. Offsets are clamped to the range of
filter#.level (-30 .. +12 dB); the data file (no audio) is committed so that the table can be regenerated.

--drive: a second measurement (fit_filter.py --identity-only --drive 0,25,50,75,100 --reso 0,30,60,100, made with the importer that already applies the table above and the drive makeup) gives the
level the drive adds on top of that (the ladders get much louder with drive and resonance together), averaged over the cutoffs, written to serum_filter_drive_laws.inc: the rows of
drive 0 / 25 / 50 / 75 / 100 % x the columns of resonance 0 / 30 / 60 / 100.
"""
import argparse
import json
import os

# types whose static law (a C3 saw, fixed cutoff) made the real presets WORSE in the comparison of the voice only renders (656 presets, effects removed): the score of the 33 LadderEMS presets
# fell 52.3 -> 49.4 and of the 13 HP12 presets 51.7 -> 44.3 with the law; they stay uncorrected until the cause is found (REFCOMPARE-REPORT.md section 6)
EXCLUDE = {'LadderEMS', 'HP12'}
FREQS = [0.35, 0.5, 0.65, 0.8]
RESOS = [0, 10, 20, 35, 50, 75, 100]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('measured', nargs='+')
    ap.add_argument('--drive', default='')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'core', 'serum-import', 'serum_filter_laws.inc'))
    ap.add_argument('--data', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'docs', 'ui-design', 'refcompare-filter-laws.json'))
    a = ap.parse_args()
    recs = []
    for m in a.measured:
        recs += json.load(open(m))
    tab = {}
    for r in recs:
        if r['drive'] != 0:
            continue
        tab.setdefault(r['type'], {})[(r['freq'], int(r['serum_reso']))] = r['identity_rms_offset_db']
    out = {}
    for t, v in sorted(tab.items()):
        grid = []
        for f in FREQS:
            row = []
            for rs in RESOS:
                row.append(round(max(-30.0, min(12.0, v.get((f, rs), 0.0))), 1))
            grid.append(row)
        if t not in EXCLUDE and max(abs(x) for row in grid for x in row) >= 1.0:
            out[t] = grid
    json.dump({'freqs': FREQS, 'resonances': RESOS, 'unit': 'dB, Serum - ours, sustain rms of a C3 saw through the filter (identity mapping)', 'types': out}, open(a.data, 'w'), indent=1)
    with open(a.out, 'w') as f:
        f.write('// Generated by tools/ref-compare/make_filter_laws.py from docs/ui-design/refcompare-filter-laws.json: the level difference (Serum 2.1.5 - ours, dB) of a filter type by the Serum\n')
        f.write('// cutoff (rows 0.35 / 0.5 / 0.65 / 0.8) and resonance (columns 0 / 10 / 20 / 35 / 50 / 75 / 100). Do not edit.\n')
        for t, grid in out.items():
            f.write('{ "%s", { ' % t + ', '.join('{ ' + ', '.join('%.1ff' % x for x in row) + ' }' for row in grid) + ' } },\n')
    print('%d types written to %s' % (len(out), a.out))
    if a.drive:
        DRIVES, DRESOS = [0, 25, 50, 75, 100], [0, 30, 60, 100]
        acc = {}
        for r in json.load(open(a.drive)):
            acc.setdefault(r['type'], {}).setdefault((int(r['drive']), int(r['serum_reso'])), []).append(r['identity_rms_offset_db'])
        dout = {}
        for t, v in sorted(acc.items()):
            grid = [[round(max(-30.0, min(20.0, sum(v[(dr, rs)]) / len(v[(dr, rs)]))), 1) if (dr, rs) in v else 0.0 for rs in DRESOS] for dr in DRIVES]
            if t not in EXCLUDE and max(abs(x) for row in grid for x in row) >= 1.5:
                dout[t] = grid
        data = json.load(open(a.data))
        data['drive'] = {'drives': DRIVES, 'resonances': DRESOS, 'unit': 'dB, Serum - ours after the table above and the drive makeup', 'types': dout}
        json.dump(data, open(a.data, 'w'), indent=1)
        path = os.path.join(os.path.dirname(a.out), 'serum_filter_drive_laws.inc')
        with open(path, 'w') as f:
            f.write('// Generated by tools/ref-compare/make_filter_laws.py (--drive) from docs/ui-design/refcompare-filter-laws.json: the level the drive adds (Serum 2.1.5 - ours, dB) by the Serum drive\n')
            f.write('// (rows 0 / 25 / 50 / 75 / 100) and resonance (columns 0 / 30 / 60 / 100) on top of filterResoLevelDb and filterDriveMakeupDb. Do not edit.\n')
            for t, grid in dout.items():
                f.write('{ "%s", { ' % t + ', '.join('{ ' + ', '.join('%.1ff' % x for x in row) + ' }' for row in grid) + ' } },\n')
        print('%d drive types written to %s' % (len(dout), path))


if __name__ == '__main__':
    main()
