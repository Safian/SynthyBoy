#!/usr/bin/env python3
"""SynthyBoy - ref-compare: turns the measured effect laws into core/serum-import/serum_fx_laws.inc, the tables the Serum importer uses for the effect modules (serum_fx.cpp, A509).

  make_fx_laws.py MEASURED.json [--out core/serum-import/serum_fx_laws.inc] [--data docs/ui-design/refcompare-fx-laws.json]

MEASURED.json = {"distortion": {mode: [{"d": serum drive, "k": our drive, "err": harmonic shape error dB, "gain": dB, "id_gain": dB at the identity drive}, ...]},
                 "hyper": {unison: dB}, "wet": {"FXChorus": dB, ...}}
Every number is Serum 2.1.5 minus ours in dB of the sustain rms of a C3 saw at 100 % wet (the wet gain of the module); the importer remaps the mix and the level of the module so that the dry
signal stays at unity and the wet signal gets that gain (serum_fx.cpp). A distortion drive point whose harmonic shape does not follow ours (error over 2.5 dB) keeps the identity drive (0.3 x the Serum
drive) and the gain measured there. The data file (no audio) is committed so that the table can be regenerated.
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FX_ORDER = ['FXChorus', 'FXComp', 'FXDelay', 'FXDistortion', 'FXEQ', 'FXFilter', 'FXFlanger', 'FXPhaser', 'FXReverb', 'FXHyperD', 'FXUtils', 'FXBode', 'FXConv']   # = fx type 1 .. 13


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('measured')
    ap.add_argument('--out', default=os.path.join(HERE, '..', '..', 'core', 'serum-import', 'serum_fx_laws.inc'))
    ap.add_argument('--data', default=os.path.join(HERE, '..', '..', 'docs', 'ui-design', 'refcompare-fx-laws.json'))
    a = ap.parse_args()
    m = json.load(open(a.measured))
    json.dump(m, open(a.data, 'w'), indent=1, sort_keys=True)
    with open(a.out, 'w') as f:
        f.write('// Generated by tools/ref-compare/make_fx_laws.py from docs/ui-design/refcompare-fx-laws.json (Serum 2.1.5 - ours, dB, a C3 saw at 100 % wet). Do not edit.\n')
        f.write('// SB_DIST_ROWS: per distortion mode the points (Serum drive 0 .. 100, our drive 0 .. 30 dB, gain of the wet signal in dB); SB_HYPER_GAINS: the wet gain of the Hyper / Dimension module by the\n')
        f.write('// unison count 0 .. 7; SB_WET_GAINS: the wet gain by module type (the order of FxInstanceType 1 .. 13).\n')
        f.write('#define SB_DIST_ROWS \\\n')
        for mode, rows in sorted(m['distortion'].items()):
            pts = []
            for r in rows:
                ok = r['err'] <= 2.5
                k = r['k'] if ok else 0.3 * r['d']
                g = r['gain'] if ok else r['id_gain']
                g = max(-60.0, min(24.0, g))
                pts.append('{ %g, %.1f, %.1f }' % (r['d'], k, g))
            f.write('    { "%s", { %s } }, \\\n' % (mode, ', '.join(pts)))
        f.write('\n')
        # the mix laws: per module type (FxInstanceType 1 .. 13) the Serum law (the dry and the wet gain by the Wet knob 0 .. 100 in steps of 5, relative to the dry and to the 100 % wet render) and
        # the raw law of our module (the same by our mix knob)
        f.write('#define SB_MIX_TABLES \\\n')
        for t, name in enumerate(FX_ORDER, 1):
            if name not in m.get('mix', {}):
                f.write('    { %d, {}, {}, {}, {}, {} }, \\\n' % t)
                continue
            s, o = m['mix'][name]['serum'], m['mix'][name]['ours']
            f.write('    { %d, { %s }, { %s }, { %s }, { %s }, { %s } }, \\\n' % (t, ', '.join('%g' % r[0] for r in s), ', '.join('%.4f' % r[1] for r in s), ', '.join('%.4f' % r[2] for r in s),
                                                                                  ', '.join('%.4f' % r[1] for r in o), ', '.join('%.4f' % r[2] for r in o)))
        f.write('\n')
        f.write('#define SB_HYPER_GAINS ' + ', '.join('%.1f' % m['hyper'][str(n)] for n in range(8)) + '\n')
        f.write('#define SB_WET_GAINS ' + ', '.join('%.1f' % m['wet'].get(n, 0.0) for n in FX_ORDER) + '\n')
    print('written', a.out)


if __name__ == '__main__':
    main()
